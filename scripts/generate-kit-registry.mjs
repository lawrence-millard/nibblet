import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve("src/components/kit");
const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, "catalog.json"), "utf8"));

const UPSTREAM = ["nib", "ble"].join("");
const upstreamName = new RegExp(`\\b${UPSTREAM}(?:'s|’s)?\\b`, "gi");
const upstreamHost = new RegExp(`\\b${UPSTREAM}\\.lat\\b`, "gi");

function cleanDescription(text) {
  return String(text || "")
    .replace(upstreamName, "")
    .replace(upstreamHost, "")
    .replace(/\s{2,}/g, " ")
    .replace(/\s+([,.])/g, "$1")
    .trim();
}

const entries = catalog.map((item) => {
  const id = item.id;
  const usagePath = path.join(ROOT, id, "USAGE.tsx");
  const componentPath = path.join(ROOT, id, "Component.jsx");
  if (!fs.existsSync(usagePath) || !fs.existsSync(componentPath)) {
    throw new Error(`Missing USAGE or Component for ${id}`);
  }
  return {
    id,
    name: String(item.name || id).replace(upstreamName, "").replace(/\s{2,}/g, " ").trim(),
    description: cleanDescription(item.description),
    category: item.category || (item.categories && item.categories[0]) || "Components",
    wide: Boolean(item.wide),
  };
});

const registryTs = `/* Auto-generated by scripts/generate-kit-registry.mjs — do not edit by hand. */
import type { ComponentType } from "react";

export type KitComponentMeta = {
  id: string;
  name: string;
  description: string;
  category: string;
  wide?: boolean;
};

export const kitCatalog: KitComponentMeta[] = ${JSON.stringify(entries, null, 2)};

type DemoModule = { default: ComponentType };

export const kitDemoLoaders: Record<string, () => Promise<DemoModule>> = {
${entries
  .map(
    (e) =>
      `  ${JSON.stringify(e.id)}: () => import("@/components/kit/${e.id}/USAGE") as Promise<DemoModule>,`,
  )
  .join("\n")}
};

export const kitComponentLoaders: Record<string, () => Promise<Record<string, unknown>>> = {
${entries
  .map(
    (e) =>
      `  ${JSON.stringify(e.id)}: () => import("@/components/kit/${e.id}/Component"),`,
  )
  .join("\n")}
};
`;

fs.writeFileSync(path.join(ROOT, "registry.ts"), registryTs);
console.log("wrote registry for", entries.length, "components");

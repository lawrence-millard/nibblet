import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve("src/components/nibble");
const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, "catalog.json"), "utf8"));

const entries = catalog.map((item) => {
  const id = item.id;
  const usagePath = path.join(ROOT, id, "USAGE.tsx");
  const componentPath = path.join(ROOT, id, "Component.jsx");
  if (!fs.existsSync(usagePath) || !fs.existsSync(componentPath)) {
    throw new Error(`Missing USAGE or Component for ${id}`);
  }
  return {
    id,
    name: item.name,
    description: item.description || "",
    category: item.category || (item.categories && item.categories[0]) || "Components",
    wide: Boolean(item.wide),
  };
});

const registryTs = `/* Auto-generated by scripts/generate-nibble-registry.mjs — do not edit by hand. */
import type { ComponentType } from "react";

export type NibbleComponentMeta = {
  id: string;
  name: string;
  description: string;
  category: string;
  wide?: boolean;
};

export const nibbleCatalog: NibbleComponentMeta[] = ${JSON.stringify(entries, null, 2)};

type DemoModule = { default: ComponentType };

export const nibbleDemoLoaders: Record<string, () => Promise<DemoModule>> = {
${entries
  .map(
    (e) =>
      `  ${JSON.stringify(e.id)}: () => import("@/components/nibble/${e.id}/USAGE") as Promise<DemoModule>,`,
  )
  .join("\n")}
};

export const nibbleComponentLoaders: Record<string, () => Promise<Record<string, unknown>>> = {
${entries
  .map(
    (e) =>
      `  ${JSON.stringify(e.id)}: () => import("@/components/nibble/${e.id}/Component"),`,
  )
  .join("\n")}
};
`;

fs.writeFileSync(path.join(ROOT, "registry.ts"), registryTs);
console.log("wrote registry for", entries.length, "components");
